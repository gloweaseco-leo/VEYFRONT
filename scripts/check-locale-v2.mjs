import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')
const proxy = read('proxy.ts')
const meta = read('lib/locale-metadata.ts')
const sitemap = read('app/sitemap.ts')
const layout = read('app/layout.tsx')
const dictionary = read('lib/i18n.tsx')
const toggle = read('components/l2m/brand.tsx')
const link = read('components/l2m/localized-link.tsx')
const seoMonitor = read('scripts/seo-live-audit.mjs')
const acquisition = read('lib/acquisition-channel.ts')

assert.match(proxy, /NextResponse\.redirect\(target, 308\)/, 'legacy /zh must redirect permanently')
assert.match(proxy, /NextResponse\.rewrite\(target/, 'new /en paths must rewrite')
assert.match(proxy, /forwardedHeaders\.set\('x-vf-page-locale', 'en'\)/)
assert.match(proxy, /publicPages\.has\(suffix\)/, 'only allowlisted public pages are localized')
assert.match(proxy, /matcher: \['\/en', '\/en\/:path\*', '\/zh', '\/zh\/:path\*'\]/)
assert.match(layout, /get\('x-vf-page-locale'\) === 'en' \? 'en' : 'zh'/)
assert.match(dictionary, /initialLang = 'zh'/)
assert.match(link, /lang === 'en' && internal \? '\/en'/)
assert.match(toggle, /o\.value === 'en' \? '\/en'/)
assert.match(toggle, /hrefLang=\{o\.value === 'zh' \? 'zh-CN' : 'en'\}/)

assert.match(meta, /get\('x-vf-page-locale'\) !== 'en'/)
assert.match(meta, /canonical = origin \+ \(chinese \? '' : '\/en'\) \+ suffix/)
assert.match(meta, /const english = origin \+ '\/en' \+ suffix/)
assert.match(meta, /const zh = origin \+ suffix/)
assert.match(meta, /'x-default': zh/)
assert.match(meta, /canonical,/)
assert.match(sitemap, /const english = 'https:\/\/veyfront\.com\/en' \+ suffix/)
assert.match(sitemap, /const chinese = 'https:\/\/veyfront\.com' \+ suffix/)
assert.match(sitemap, /'x-default': chinese/)
assert.doesNotMatch(sitemap, /\/zh/)
assert.match(seoMonitor, /await page\('\/en' \+ \(path === '\/' \? '' : path\), true\)/)
assert.match(seoMonitor, /response\.status === 308/)
assert.match(seoMonitor, /'x-default'\] === expectedZh/)
assert.match(acquisition, /legacyLandingPaths/, 'retain historical /zh acquisition records')
assert.match(acquisition, /'\/en\/pricing'/)
assert.match(read('app/pricing/page.tsx'), /<PricingV35 \/>/, 'V3.5 pricing content must remain intact')
assert.match(read('lib/seo-release.ts'), /index: false, follow: false/, 'Preview must remain noindex')
console.log('VEYFRONT Locale V2 static contract PASS (browser/SEO migration acceptance remains separate)')
