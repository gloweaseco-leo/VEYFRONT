#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = p => readFileSync(p,'utf8')
const seo=read('lib/seo-release.ts')
const robots=read('app/robots.ts')
const sitemap=read('app/sitemap.ts')
const meta=read('lib/locale-metadata.ts')
assert.match(seo,/VERCEL_ENV === 'production'/)
assert.match(seo,/index: true, follow: true/)
assert.match(seo,/index: false, follow: false/)
assert.match(robots,/if \(!isPublicRelease\)/)
assert.match(robots,/disallow: '\/'/)
assert.match(robots,/allow: '\/'/)
assert.doesNotMatch(robots,/disallow:\s*\[/,'Production robots must not hide review noindex metadata')
assert.match(sitemap,/if \(!isPublicRelease\) return \[\]/)
for (const path of ['/pricing','/how-it-works','/contact','/start/launch','/start/rebuild','/privacy','/terms'])
  assert.ok(sitemap.includes(path),'Public path omitted '+path)
assert.doesNotMatch(sitemap,/\/transformations.*?[,\]]/)
assert.doesNotMatch(sitemap,/['"]\/services['"]/,'Do not sitemap a permanent redirect')
assert.match(meta,/robots: Metadata\['robots'\] = releaseRobots/)
assert.match(read('app/pricing/page.tsx'),/localizedMetadata\(/)
assert.match(read('app/page.tsx'),/localizedMetadata\(/)
assert.match(read('app/transformations/page.tsx'),/index: false/)
console.log('VEYFRONT production/preview indexing policy and sitemap guards PASS')
